#!/usr/bin/env bash
# Bakes specialized variants of the engine's three/shaders/three.wgsl for
# the program keys the gallery's examples draw ("optimized" mode, PLAN.md
# M14): it records keys by running packages/gallery (which builds the
# engine from packages/threeas, its library override) and writes the
# variants into packages/threeas. The uber-shader
# stays the default and the fallback: GPURenderer uses a baked variant only
# for a draw whose key was baked from the current three.wgsl.
#
#   tools/bake_shaders.sh                  record every example artboard and bake
#   tools/bake_shaders.sh --gallery=DIR    record another gallery checkout
#   tools/bake_shaders.sh Lights Shadows   record only these artboards
#   tools/bake_shaders.sh --keys=keys.txt  also bake keys from a file (one per
#                                          line, e.g. copied from the "no baked
#                                          shader for <key>" log of a dev build)
#   tools/bake_shaders.sh --max=64         cap the variant count (default 48)
#   tools/bake_shaders.sh --check          bake into build/ and fail if the
#                                          committed variants differ (CI)
#   tools/bake_shaders.sh --clean          remove every variant (uber-shader only)
#
# 1. Records: runs the artboards headless with `--arg threeShaderKeys=1`
#    (one build, `rive --commands`); the renderer logs each program key it
#    draws once ("three shader key: kind=3;present=1;...;lights=dp").
# 2. Generates three/shaders/baked/three_v_<hash>.wgsl per key (paths in
#    packages/threeas from here on): three.wgsl
#    with the lines between `// @variant-begin` and `// @variant-end`
#    replaced by functions returning the key's constants (the shading
#    model, maps, flags, discard or not, the light count and types), so the
#    compiler drops dead branches and samples, keeps `discard` out of
#    pipelines that never cut out, and unrolls the light loop. The bind
#    group layouts stay the uber-shader's.
# 3. Writes the registry, three/renderers/gpu/BakedShaders.as: the keys,
#    their assets, and the hash of the three.wgsl they came from (compared
#    at runtime with THREE_WGSL_HASH, which tools/make_shader_chunks.py
#    writes). .wgsl files register themselves as shader assets: no RML.
#
# Then republish the engine library, build a release .riv of the gallery
# and run tools/check_glsl.py on it (WebGL2); tools/publish.sh does both.
set -euo pipefail
cd "$(dirname "$0")/.."

ENGINE=packages/threeas
GALLERY=packages/gallery
SRC=$ENGINE/three/shaders/three.wgsl
OUT=$ENGINE/three/shaders/baked
REG=$ENGINE/three/renderers/gpu/BakedShaders.as
HASH_FILE=$ENGINE/three/renderers/gpu/ShaderSourceHash.as
WORK=build/bake
max=48
mode=bake
keys_file=""
artboards=()
for arg in "$@"; do
    case "$arg" in
        --max=*) max="${arg#--max=}" ;;
        --keys=*) keys_file="${arg#--keys=}" ;;
        --check) mode=check ;;
        --gallery=*) GALLERY="${arg#--gallery=}" ;;
        --clean) mode=clean ;;
        -h|--help) sed -n '2,38p' "$0"; exit 0 ;;
        -*) echo "unknown option $arg" >&2; exit 2 ;;
        *) artboards+=("$arg") ;;
    esac
done

hash=$(shasum -a 256 "$SRC" | cut -c1-16)

write_registry() {   # $1: registry path, $2: source hash, $3: keys file (key<TAB>asset)
    local reg="$1" src_hash="$2" list="$3"
    {
        echo "// Generated by tools/bake_shaders.sh: the baked shader variants of"
        echo "// three/shaders/three.wgsl (program key -> shader asset). Do not edit."
        echo "//"
        if [ ! -s "$list" ]; then
            echo "// Empty: no variants are baked, and GPURenderer draws everything with the"
            echo "// uber-shader. Run tools/bake_shaders.sh to bake the variants a project"
            echo "// draws (\"optimized\" mode); \`tools/bake_shaders.sh --clean\` empties it again."
        else
            echo "// $(wc -l < "$list" | tr -d ' ') variants. \`tools/bake_shaders.sh --clean\` removes them (uber-shader only)."
        fi
        echo ""
        echo "/// THREE_WGSL_HASH of the three.wgsl the variants were baked from."
        echo "export const BAKED_SOURCE_HASH: string = \"$src_hash\";"
        echo "/// The program keys (GPURenderer.programKey), sorted."
        if [ ! -s "$list" ]; then
            echo "export const BAKED_KEYS: StaticArray<string> = [];"
            echo "/// The shader asset of each key (three/shaders/baked/<name>.wgsl)."
            echo "export const BAKED_ASSETS: StaticArray<string> = [];"
        else
            echo "export const BAKED_KEYS: StaticArray<string> = ["
            cut -f1 "$list" | sed 's/.*/    "&",/'
            echo "];"
            echo "/// The shader asset of each key (three/shaders/baked/<name>.wgsl)."
            echo "export const BAKED_ASSETS: StaticArray<string> = ["
            cut -f2 "$list" | sed 's/.*/    "&",/'
            echo "];"
        fi
    } > "$reg"
}

if [ "$mode" = clean ]; then
    rm -rf "$OUT"
    : > "$WORK.empty" 2>/dev/null || { mkdir -p build; : > "$WORK.empty"; }
    write_registry "$REG" "" "$WORK.empty"
    rm -f "$WORK.empty"
    echo "removed the baked variants; the uber-shader draws everything"
    exit 0
fi

if ! grep -q "\"$hash\"" "$HASH_FILE"; then
    echo "$HASH_FILE is not three.wgsl's hash ($hash): run python3 tools/make_shader_chunks.py first" >&2
    exit 1
fi

if [ "$mode" = check ] && grep -q "BAKED_KEYS: StaticArray<string> = \[\];" "$REG"; then
    echo "no baked shader variants committed (uber-shader only): nothing to check"
    exit 0
fi

# ------------------------------------------------------------------ record
mkdir -p "$WORK"
if [ "$mode" = bake ]; then
    # Record with the uber-shader only (old variants may not even build).
    rm -rf "$OUT"
    : > "$WORK/empty.tsv"
    write_registry "$REG" "" "$WORK/empty.tsv"
fi
if [ ${#artboards[@]} -eq 0 ]; then
    while IFS= read -r a; do artboards+=("$a"); done < <(cat "$GALLERY"/examples/*/*.rml \
        | grep -o '<Artboard isComponent="true"[^>]*name="[^"]*"' | sed 's/.*name="\([^"]*\)"/\1/')
fi
commands="$WORK/commands.txt"
: > "$commands"
for a in "${artboards[@]}"; do
    printf 'artboard %s\nadvance 1s\nscreenshot %s/shot.png\nadvance 2s\nscreenshot %s/shot.png\n' \
        "$a" "$WORK" "$WORK" >> "$commands"
done
echo "quit" >> "$commands"
echo "recording ${#artboards[@]} artboards..."
if ! rive "$GALLERY" --commands="$commands" --arg threeShaderKeys=1 > "$WORK/record.log" 2>&1; then
    echo "rive failed; see $WORK/record.log" >&2
    exit 1
fi
if grep -q "falling back to the downloaded library" "$WORK/record.log"; then
    echo "the gallery did not build packages/threeas (its library override was refused):" >&2
    grep "falling back" "$WORK/record.log" >&2
    exit 1
fi
if grep -q "^err" "$WORK/record.log"; then
    grep "^err" "$WORK/record.log" >&2
    exit 1
fi
# Each artboard's renderer logs a key once, so a key's count is how many
# artboards draw it: past --max, the most shared keys are baked.
{
    sed -n 's/.*three shader key: \(kind=[^ ]*\).*/\1/p' "$WORK/record.log"
    if [ -n "$keys_file" ]; then sed -n 's/.*\(kind=[^ ]*;fs=[a-z_]*\).*/\1/p' "$keys_file"; fi
} | LC_ALL=C sort | uniq -c | LC_ALL=C sort -k1,1nr -k2 > "$WORK/keys.counted"
count=$(wc -l < "$WORK/keys.counted" | tr -d ' ')
if [ "$count" -gt "$max" ]; then
    echo "warning: $count program keys, baking the $max most shared (raise --max to bake them all)" >&2
    count=$max
fi
head -n "$max" "$WORK/keys.counted" | awk '{ print $2 }' | LC_ALL=C sort > "$WORK/keys.txt"

# ---------------------------------------------------------------- generate
bool() { [ "$1" = 1 ] && echo true || echo false; }

# A key's entry points, comma separated (its vs= and fs= fields).
entry_points() {
    local key="$1" vs fs
    vs=$(printf '%s' "$key" | sed -n 's/.*;vs=\([a-z_]*\).*/\1/p')
    fs=$(printf '%s' "$key" | sed -n 's/.*;fs=\([a-z_]*\).*/\1/p')
    echo "${vs:-vs_main},${fs:-fs_main}"
}

# three.wgsl with the variant block replaced and only the key's two entry
# points (a variant draws one pipeline family; each entry point costs a
# compiled shader per backend in the .riv). A vertex entry that does not
# skin (or morph) keeps the bone (and morph) block bound by reading one
# value of it: the layouts are the uber-shader's.
specialize() {   # $1: block file, $2: entry points
    awk -v block="$1" -v keep="$2" '
        BEGIN { n = split(keep, names, ","); for (i = 1; i <= n; i++) wanted[names[i]] = 1 }
        /\/\/ @variant-begin/ { while ((getline line < block) > 0) print line; skip = 1; next }
        /\/\/ @variant-end/ { skip = 0; next }
        skip { next }
        /^@vertex$|^@fragment$/ { attr = $0; pending = 1; next }
        pending {
            pending = 0
            name = $0; sub(/^fn /, "", name); sub(/\(.*/, "", name)
            if (!(name in wanted)) { dropping = 1; next }
            print attr; print
            if (attr == "@vertex" && name !~ /skinned/) print "    let keep_bones = B.bones[0][0].x;"
            if (attr == "@vertex" && name !~ /vs_main|vs_displaced|skinned/) print "    let keep_morph = M.info.x;"
            next
        }
        dropping { if ($0 == "}") dropping = 0; next }
        { print }
    ' "$SRC"
}

# The variant block for one key, on stdout.
variant_block() {
    local key="$1" kind=0 present=0 roles=0 flags=0 cutout=1 flat=0 env=0 scene=0 fog=0 hemi=0 linear=0 lights=-
    local IFS=';'
    for field in $key; do
        local name="${field%%=*}" value="${field#*=}"
        case "$name" in
            kind) kind=$value ;; present) present=$value ;; roles) roles=$value ;; flags) flags=$value ;;
            cutout) cutout=$value ;; flat) flat=$value ;; env) env=$value ;; scene) scene=$value ;;
            fog) fog=$value ;; hemi) hemi=$value ;; linear) linear=$value ;; lights) lights=$value ;;
            vs|fs) ;;   # the entry points: kept by entry_points
            *) echo "unknown key field $name in $key" >&2; return 1 ;;
        esac
    done
    unset IFS
    [ "$lights" = "-" ] && lights=""
    echo "// @variant-begin"
    echo "// Baked by tools/bake_shaders.sh for $key"
    echo "fn v_kind() -> u32 { return ${kind}u; }"
    echo "fn v_present() -> u32 { return ${present}u; }"
    echo "fn v_flags() -> u32 { return ${flags}u; }"
    echo "fn v_role(role: u32) -> bool { return ((${roles}u >> role) & 1u) != 0u; }"
    echo "fn v_cutout() -> bool { return $(bool "$cutout"); }"
    echo "fn v_flat() -> bool { return $(bool "$flat"); }"
    echo "fn v_own_env() -> bool { return $(bool "$env"); }"
    echo "fn v_scene_env() -> bool { return $(bool "$scene"); }"
    echo "fn v_fog() -> f32 { return ${fog}.0; }"
    echo "fn v_hemi() -> bool { return $(bool "$hemi"); }"
    echo "fn v_linear() -> bool { return $(bool "$linear"); }"
    echo "fn v_light_count() -> u32 { return ${#lights}u; }"
    echo "fn v_light_type(k: u32, light: Light) -> f32 {"
    local i
    for ((i = 0; i < ${#lights}; i++)); do
        local t=0.0
        case "${lights:i:1}" in d) t=0.0 ;; p) t=1.0 ;; s) t=2.0 ;; r) t=3.0 ;; esac
        echo "    if (k == ${i}u) { return $t; }"
    done
    echo "    return 0.0;"
    echo "}"
    echo "// @variant-end"
}

if [ "$mode" = check ]; then
    out="$WORK/check/baked"
    reg="$WORK/check/BakedShaders.as"
else
    out="$OUT"
    reg="$REG"
fi
rm -rf "$out"
mkdir -p "$out" "$(dirname "$reg")"
list="$WORK/registry.tsv"
: > "$list"
while IFS= read -r key; do
    [ -z "$key" ] && continue
    name="three_v_$(printf '%s' "$key" | shasum | cut -c1-10)"
    variant_block "$key" > "$WORK/block.wgsl"
    {
        echo "// Generated by tools/bake_shaders.sh from three/shaders/three.wgsl ($hash):"
        echo "// the uber-shader specialized for one program key. Do not edit; rebake."
        specialize "$WORK/block.wgsl" "$(entry_points "$key")"
    } > "$out/$name.wgsl"
    printf '%s\t%s\n' "$key" "$name" >> "$list"
done < "$WORK/keys.txt"
write_registry "$reg" "$hash" "$list"

if [ "$mode" = check ]; then
    if diff -r -q "$out" "$OUT" > /dev/null 2>&1 && diff -q "$reg" "$REG" > /dev/null 2>&1; then
        echo "baked shaders are fresh ($count variants)"
        exit 0
    fi
    echo "baked shaders are stale: rerun tools/bake_shaders.sh (or --clean)" >&2
    exit 1
fi
echo "baked $count variants into $OUT ($(du -sh "$OUT" | cut -f1)); registry $REG"
echo "next: rive packages/threeas --verify, then tools/publish.sh (release build, check_glsl.py, publish)"
