"""Writes three/lights/RectAreaLightTables.as from three.js's
examples/jsm/lights/RectAreaLightTexturesLib.js (MIT): its LTC_MAT_1 and
LTC_MAT_2 tables (64 x 64 RGBA), resampled to 32 x 32 and packed as half
floats so both fit one 16 KB uniform block.

    curl -sSfLO https://raw.githubusercontent.com/mrdoob/three.js/r170/examples/jsm/lights/RectAreaLightTexturesLib.js
    python3 -I tools/make_ltc_tables.py RectAreaLightTexturesLib.js   # in packages/threeas

The input is only parsed for its two number arrays, never executed.
"""
import os, re, struct, sys

src = open(sys.argv[1]).read()
data = {n: [float(x) for x in re.findall(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", a)]
        for n, a in re.findall(r"const (LTC_MAT_[12]) = \[(.*?)\];", src, re.S)}
m1, m2 = data["LTC_MAT_1"], data["LTC_MAT_2"]
assert len(m1) == len(m2) == 64 * 64 * 4

def sample(m, u, v):
    x0, y0 = int(u), int(v)
    x1, y1 = min(63, x0 + 1), min(63, y0 + 1)
    fx, fy = u - x0, v - y0
    out = []
    for c in range(4):
        a = m[(y0 * 64 + x0) * 4 + c] * (1 - fx) + m[(y0 * 64 + x1) * 4 + c] * fx
        b = m[(y1 * 64 + x0) * 4 + c] * (1 - fx) + m[(y1 * 64 + x1) * 4 + c] * fx
        out.append(a * (1 - fy) + b * fy)
    return out

words = []
for y in range(32):
    for x in range(32):
        # texel i of 32 sits at parameter i / 31, like texel j of 64 at j / 63
        u, v = x / 31 * 63, y / 31 * 63
        h = [struct.unpack("<H", struct.pack("<e", f))[0] for f in sample(m1, u, v) + sample(m2, u, v)]
        words += [h[0] | h[1] << 16, h[2] | h[3] << 16, h[4] | h[5] << 16, h[6] | h[7] << 16]
lines = ["    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + "," for i in range(0, len(words), 8)]
out = os.path.join(os.path.dirname(__file__), "..", "three", "lights", "RectAreaLightTables.as")
open(out, "w").write('''// The linearly transformed cosines tables three.js's RectAreaLight uses
// (examples/jsm/lights/RectAreaLightTexturesLib.js, MIT; the fits are Eric
// Heitz, Jonathan Dupuy, Stephen Hill and David Neubelt's, "Real-Time
// Polygonal-Light Shading with Linearly Transformed Cosines", 2016),
// resampled from 64 x 64 to 32 x 32 to fit a 16 KB uniform block: per
// texel (roughness, sqrt(1 - n.v)), LTC_MAT_1 then LTC_MAT_2, as four
// pack2x16float words. Generated by tools/make_ltc_tables.py.

export const LTC_SIZE: i32 = 32;

export const LTC_TABLE: StaticArray<u32> = [
''' + "\n".join(lines) + "\n];\n")
print("wrote", out)
